CREATE TABLE IF NOT EXISTS public.produto (
    id_produto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    preco NUMERIC(10, 2) NOT NULL CHECK (preco > 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE public.produto
    ADD COLUMN IF NOT EXISTS descricao VARCHAR(500) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS imagem_url VARCHAR(500);

CREATE TABLE IF NOT EXISTS public.pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_operario INTEGER,
    tipo_atendimento VARCHAR(40) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Pendente',
    valor_total NUMERIC(10, 2) NOT NULL CHECK (valor_total >= 0),
    forma_pagamento VARCHAR(50) NOT NULL DEFAULT '',
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_conclusao TIMESTAMPTZ
);

ALTER TABLE public.pedido
    ADD COLUMN IF NOT EXISTS cliente_nome VARCHAR(100),
    ADD COLUMN IF NOT EXISTS cliente_telefone VARCHAR(30),
    ADD COLUMN IF NOT EXISTS endereco_entrega VARCHAR(300),
    ADD COLUMN IF NOT EXISTS id_caixa BIGINT,
    ADD COLUMN IF NOT EXISTS itens JSONB NOT NULL DEFAULT '[]'::jsonb;

CREATE TABLE IF NOT EXISTS public.caixa (
    id_caixa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_operario_abertura INTEGER NOT NULL,
    abertura_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    valor_inicial NUMERIC(10, 2) NOT NULL CHECK (valor_inicial >= 0),
    fechamento_em TIMESTAMPTZ,
    valor_informado NUMERIC(10, 2) CHECK (valor_informado >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Aberto' CHECK (status IN ('Aberto', 'Fechado')),
    observacao_fechamento VARCHAR(500) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS ix_caixa_status_abertura ON public.caixa (status, abertura_em DESC);
CREATE INDEX IF NOT EXISTS ix_pedido_id_caixa ON public.pedido (id_caixa);

ALTER TABLE public.pedido
    ALTER COLUMN id_operario DROP NOT NULL;

CREATE TABLE IF NOT EXISTS public.item_pedido (
    id_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES public.pedido(id_pedido) ON DELETE CASCADE,
    id_produto BIGINT NOT NULL REFERENCES public.produto(id_produto),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10, 2) NOT NULL CHECK (preco_unitario >= 0),
    observacao VARCHAR(300) NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS ix_pedido_data_criacao ON public.pedido (data_criacao DESC);
CREATE INDEX IF NOT EXISTS ix_produto_ativo_categoria ON public.produto (ativo, categoria);
CREATE INDEX IF NOT EXISTS ix_item_pedido_id_pedido ON public.item_pedido (id_pedido);

ALTER TABLE public.produto ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pedido ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.item_pedido ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public_read_active_products" ON public.produto;
CREATE POLICY "public_read_active_products"
    ON public.produto FOR SELECT TO anon, authenticated
    USING (ativo = TRUE);
